/**
 * Server-signed, replay-proof game snapshots (bug B19, plan §4a).
 *
 * Today `server.js:569` takes a `gameState` straight off the wire in a
 * `restore_game` event and installs it into a room — any client can fabricate
 * money and property ownership. Resume is kept (the user chose signed
 * snapshots over deleting it), but the client now only ever holds an
 * **opaque, signed blob** it cannot forge or usefully replay:
 *
 *   - Signed with `crypto.createHmac('sha256', secret)` over canonical
 *     (sorted-key) JSON, so re-serialising the same payload from a different
 *     code path can never produce different bytes and silently break the sig.
 *   - Compared with `crypto.timingSafeEqual`, never `===`.
 *   - Version-gated: `payload.stateVersion` must be STRICTLY greater than the
 *     highest version ever restored for that room (persisted in
 *     `versionStore.ts`). Signing alone does not stop replay — a player could
 *     otherwise hoard a legitimately-signed early snapshot from when they were
 *     rich and restore it later. An EQUAL version is rejected too: restoring
 *     consumes the version, it is not free to repeat.
 *   - TTL- and participant-checked.
 *
 * Every rejection path returns a typed `RestoreRejection` (the same type
 * `shared/events.ts` puts on the wire in `restore_rejected`) and NEVER
 * installs state. This module is pure with respect to the rest of the
 * server — secret / version store / room-liveness are passed in, and it never
 * touches socket.io, express, or a live room registry itself. Wiring a
 * `RestoreResult` into socket handlers (installing `payload.state`, seating
 * the requester, deciding what "still live" means) is a separate concern.
 */
import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { SignedSnapshot, RestoreRejection } from '../shared/events.js';
import type { GameState, SeatId } from '../shared/types.js';
import { SNAPSHOT_TTL_MS } from '../shared/rules.js';
import type { VersionStore } from './versionStore.js';

export type { SignedSnapshot, RestoreRejection };

export interface SnapshotPayload {
  roomCode: string;
  stateVersion: number;
  /** Epoch milliseconds. */
  issuedAt: number;
  seatIds: readonly SeatId[];
  state: GameState;
}

export type RestoreResult =
  | { ok: true; payload: SnapshotPayload }
  | { ok: false; reason: RestoreRejection };

export interface RestoreContext {
  now: number;
  ttlMs?: number;
  /**
   * True if a live room already exists for the snapshot's `roomCode`. Restore
   * must not clobber a live room — the caller should route to a plain rejoin
   * instead of treating this as a rejection of the snapshot itself.
   */
  isRoomLive: (roomCode: string) => boolean;
  versionStore: VersionStore;
  requesterSeatId: SeatId;
}

// ── Secret (BANKELHAZ_SECRET env, else a persisted, auto-generated one) ──

export interface LoadedSecret {
  secret: Buffer;
  autoGenerated: boolean;
}

const SECRET_BYTES = 32;
const SECRET_FILE_MODE = 0o600;

/**
 * Resolution order: `BANKELHAZ_SECRET` env var; else a secret previously
 * persisted at `<dataDir>/secret`; else 32 fresh random bytes, persisted
 * there at mode 0600 so dev restarts keep working, with a loud warning — an
 * auto-generated secret means every snapshot issued by a *different* process
 * (a restart without this file, or another replica) cannot be verified.
 */
export function loadOrCreateSecret(dataDir = '.data'): LoadedSecret {
  const envSecret = process.env['BANKELHAZ_SECRET'];
  if (envSecret !== undefined && envSecret.length > 0) {
    return { secret: Buffer.from(envSecret, 'utf8'), autoGenerated: false };
  }

  const secretPath = join(dataDir, 'secret');
  if (existsSync(secretPath)) {
    const hex = readFileSync(secretPath, 'utf8').trim();
    return { secret: Buffer.from(hex, 'hex'), autoGenerated: false };
  }

  mkdirSync(dataDir, { recursive: true });
  const secret = randomBytes(SECRET_BYTES);
  writeFileSync(secretPath, secret.toString('hex'), { mode: SECRET_FILE_MODE });
  // writeFileSync's `mode` is masked by the process umask; force it explicitly
  // so the secret is never left group/world-readable.
  chmodSync(secretPath, SECRET_FILE_MODE);
  console.warn(
    `[bankelhaz] BANKELHAZ_SECRET not set — auto-generated a snapshot-signing ` +
      `secret at ${secretPath}. Fine for local development; a production ` +
      `deployment should set BANKELHAZ_SECRET explicitly, otherwise every ` +
      `instance/restart-without-this-file signs with a different secret and ` +
      `existing snapshots become unverifiable.`,
  );
  return { secret, autoGenerated: true };
}

// ── Canonical JSON ──

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value !== null && typeof value === 'object') {
    const obj = value as Record<string, unknown>;
    const sorted: Record<string, unknown> = {};
    for (const key of Object.keys(obj).sort()) sorted[key] = canonicalize(obj[key]);
    return sorted;
  }
  return value;
}

/**
 * Deterministic JSON: object keys sorted at every level, so the same payload
 * always serialises to the same bytes and a signature is reproducible.
 */
export function canonicalStringify(value: unknown): string {
  return JSON.stringify(canonicalize(value));
}

// ── Signing / verification ──

function sign(payloadB64: string, secret: Buffer): string {
  return createHmac('sha256', secret).update(payloadB64, 'utf8').digest('hex');
}

export function createSnapshot(payload: SnapshotPayload, secret: Buffer): SignedSnapshot {
  const payloadB64 = Buffer.from(canonicalStringify(payload), 'utf8').toString('base64');
  return { payload: payloadB64, sig: sign(payloadB64, secret), v: 1 };
}

/**
 * Constant-time signature check. Never throws on malformed input — a decoding
 * failure or length mismatch is treated as a failed check rather than allowed
 * to propagate, so a corrupt or forged blob fails closed.
 */
function verifySignature(snapshot: SignedSnapshot, secret: Buffer): boolean {
  let expected: Buffer;
  let actual: Buffer;
  try {
    expected = Buffer.from(sign(snapshot.payload, secret), 'hex');
    actual = Buffer.from(snapshot.sig, 'hex');
  } catch {
    return false;
  }
  if (expected.length !== actual.length) return false;
  return timingSafeEqual(expected, actual);
}

function isValidPayloadShape(value: unknown): value is SnapshotPayload {
  if (value === null || typeof value !== 'object') return false;
  const p = value as Record<string, unknown>;
  return (
    typeof p['roomCode'] === 'string' &&
    typeof p['stateVersion'] === 'number' &&
    typeof p['issuedAt'] === 'number' &&
    Array.isArray(p['seatIds']) &&
    p['state'] !== null &&
    typeof p['state'] === 'object'
  );
}

/**
 * Verify and authorise a snapshot restore. Checks, in order: signature
 * integrity, payload shape, whether the room is already live (→ caller should
 * rejoin instead), the anti-replay version gate (strictly greater — an equal
 * version is also rejected), TTL, and participant membership.
 *
 * On success, records the version as seen (bumping the persisted anti-replay
 * high-water mark for this room) — the caller is then responsible for
 * actually installing `payload.state` and seating the requester; this
 * function never mutates game state itself.
 */
export function restoreSnapshot(
  snapshot: SignedSnapshot,
  secret: Buffer,
  ctx: RestoreContext,
): RestoreResult {
  if (!verifySignature(snapshot, secret)) return { ok: false, reason: 'bad_signature' };

  let parsed: unknown;
  try {
    parsed = JSON.parse(Buffer.from(snapshot.payload, 'base64').toString('utf8'));
  } catch {
    return { ok: false, reason: 'malformed' };
  }
  if (!isValidPayloadShape(parsed)) return { ok: false, reason: 'malformed' };
  const payload = parsed;

  if (ctx.isRoomLive(payload.roomCode)) return { ok: false, reason: 'room_is_live' };

  const highest = ctx.versionStore.getHighest(payload.roomCode);
  if (payload.stateVersion <= highest) return { ok: false, reason: 'stale_version' };

  const ttlMs = ctx.ttlMs ?? SNAPSHOT_TTL_MS;
  if (ctx.now - payload.issuedAt > ttlMs) return { ok: false, reason: 'expired' };

  if (!payload.seatIds.includes(ctx.requesterSeatId)) {
    return { ok: false, reason: 'not_a_participant' };
  }

  ctx.versionStore.recordSeen(payload.roomCode, payload.stateVersion);
  return { ok: true, payload };
}
